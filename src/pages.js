export const normPath = (p) => {
  const x = (p || '/').replace(/\/index\.html$/, '').replace(/\/+$/, '')
  return x ? x + '/' : '/'
}

export const findService = (path) => SERVICE_PAGES.find((s) => s.path === path)
export const isKnown = (path) => path === '/' || !!findService(path) || !!OTHER_PAGES[path]

export function routeMeta(path) {
  if (path === '/') return null
  const s = findService(path)
  if (s) return { title: s.title, description: s.description, canonical: SITE + path }
  const o = OTHER_PAGES[path]
  if (o) return { title: o.title, description: o.description, canonical: SITE + path }
  return { title: 'העמוד לא נמצא | שורק מהנדסים יועצים', description: 'העמוד המבוקש לא נמצא.', canonical: SITE + '/', noindex: true }
}

export const ALL_PATHS = ['/', ...SERVICE_PAGES.map((s) => s.path), ...Object.keys(OTHER_PAGES)]

export function routeLd(path) {
  const s = findService(path)
  const o = OTHER_PAGES[path]
  if (!s && !o) return []
  const crumb = s ? s.nav : o.crumb
  const out = [{
    '@context': 'https://schema.org',
    '@type': 'BreadcrumbList',
    itemListElement: [
      { '@type': 'ListItem', position: 1, name: 'דף הבית', item: SITE + '/' },
      { '@type': 'ListItem', position: 2, name: crumb, item: SITE + path },
    ],
  }]
  if (s) out.push({
    '@context': 'https://schema.org',
    '@type': 'Service',
    name: s.h1,
    description: s.description,
    url: SITE + path,
    inLanguage: 'he',
    provider: { '@id': SITE + '/#org' },
    areaServed: ['חיפה', 'ישראל'],
  })
  return out
}

